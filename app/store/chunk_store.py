from langchain_core.documents import Document
from app.utils.constants import DATA_PROCESSED_DIR
import json


def save_chunks(chunks: list[Document], document_id: str) -> str:
    """
    Saves the chunks to the disk generated by the `chunking.py` file.

    Replaces old chunks with new ones.
    """
    doc_path = DATA_PROCESSED_DIR / "chunks" / f"{document_id}.jsonl"

    with open(doc_path, "w") as file:
        for chunk in chunks:
            json_chunk: dict[str, str | dict[str, str | int]] = {
                "page_content": chunk.page_content,
                "metadata": chunk.metadata,
            }
            file.write(json.dumps(json_chunk) + "\n")

    return document_id


def get_chunks(document_id: str) -> list[Document]:
    """
    Fetches all the chunks by filename containing `document_id`. Returns list of Document.
    """
    doc_path = DATA_PROCESSED_DIR / "chunks" / f"{document_id}.jsonl"

    if not doc_path.exists():
        raise FileNotFoundError(doc_path)

    doc_list: list[Document] = []

    with open(doc_path, "r") as file:
        file_content = file.readlines()

        for chunk in file_content:
            chunk_content = json.loads(chunk)
            newChunk_doc: Document = Document(**chunk_content)
            doc_list.append(newChunk_doc)

    return doc_list


def clear_chunks_store():
    """
    Empty the entire `processed/chunks` files. Leaves the folder only.
    """
    dir_path = DATA_PROCESSED_DIR / "chunks"
    dir_path.mkdir(exist_ok=True, parents=True)

    count = 0
    for f in dir_path.iterdir():
        f.unlink()
        count += 1

    print(f"[ OK ] {count} Chunk file removed. Chunk store is empty!")


if __name__ == "__main__":
    clear_chunks_store()
